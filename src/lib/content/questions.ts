export const QUESTIONS: Question[] = [
  ...MODULES.flatMap((m) => m.quiz),
  ...CASES.flatMap((c) => c.questions.map((q) => ({ ...q, tracingId: q.tracingId ?? c.tracingId }))),
  ...extra,
];

export const TOPICS = [...new Set(QUESTIONS.map((q) => q.topic))].sort();

export function examQuestions(): Question[] {
  const pool = extra.concat(MODULES.flatMap((m) => m.quiz));
  const step = Math.max(1, Math.floor(pool.length / 25));
  const picked: Question[] = [];
  for (let i = 0; i < pool.length && picked.length < 25; i += step) {
    const q = pool[i];
    if (q) picked.push(q);
  }
  return picked.slice(0, 25);
}
